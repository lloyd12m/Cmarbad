-- Categories for the existing Supabase store. Applied once to the store project.
-- All changes are atomic; deleting a category keeps its products unclassified.
begin;
create table public.categories (
  id bigint generated by default as identity primary key,
  name text not null check (length(btrim(name)) between 1 and 80),
  created_at timestamptz not null default now()
);
create unique index categories_name_unique on public.categories (lower(btrim(name)));
alter table public.categories enable row level security;
grant select on public.categories to anon, authenticated;
grant insert, update, delete on public.categories to authenticated;
grant usage, select on sequence public.categories_id_seq to authenticated;
create policy categories_public_read on public.categories for select to anon, authenticated using (true);
create policy categories_admin_insert on public.categories for insert to authenticated with check (public.is_admin());
create policy categories_admin_update on public.categories for update to authenticated using (public.is_admin()) with check (public.is_admin());
create policy categories_admin_delete on public.categories for delete to authenticated using (public.is_admin());
alter table public.products add column category_id bigint references public.categories(id) on delete set null;
create index products_category_id_idx on public.products (category_id);
insert into public.categories (name) values ('السناكات');
update public.products set category_id = (select id from public.categories where name = 'السناكات');
commit;
